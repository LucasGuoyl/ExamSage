_CATALOGS = {"en": _ENGLISH, "zh-CN": _CHINESE}
if set(_ENGLISH) != set(_CHINESE):  # pragma: no cover - import-time invariant
    raise RuntimeError("UI translation catalogs must contain the same keys")


def get_ui_language(state: Mapping[str, object]) -> str:
    value = state.get(UI_LANGUAGE_KEY, "en")
    return value if isinstance(value, str) and value in SUPPORTED_UI_LANGUAGES else "en"


def set_ui_language(state: MutableMapping[str, object], language: str) -> None:
    if language not in SUPPORTED_UI_LANGUAGES:
        raise ValueError("UI language must be supported")
    state[UI_LANGUAGE_KEY] = language


class _Text:
    def __call__(self, key: str, language: str = "en", **values: object) -> str:
        if language not in SUPPORTED_UI_LANGUAGES:
            language = "en"
        try:
            template = _CATALOGS[language][key]
        except KeyError:
            raise KeyError(f"Unknown UI text key: {key}") from None
        return template.format(**values)

    def catalog(self, language: str) -> Mapping[str, str]:
        if language not in SUPPORTED_UI_LANGUAGES:
            raise ValueError("UI language must be supported")
        return dict(_CATALOGS[language])


text = _Text()
